// Auxiliary task block with the shared shape and the request timeout
func aux(timeout int, extra map[string]any) map[string]any {
	m := map[string]any{
		"provider": "auto", "model": "", "base_url": "", "api_key": "",
		"timeout": timeout, "extra_body": map[string]any{}, "reasoning_effort": "",
	}
	for k, v := range extra {
		m[k] = v
	}
	return m
}

