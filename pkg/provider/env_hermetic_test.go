// Reports whether an env var name is credential shaped the way the hermetic test environment blanks it
func hermeticLooksLikeCredential(name string) bool {
	if hermeticCredentialNames[name] {
		return true
	}
	for _, suffix := range hermeticCredentialSuffixes {
		if strings.HasSuffix(name, suffix) {
			return true
		}
	}
	return false
}

// Blanks credential shaped and behavioral env vars for one test, each restored to its prior state afterwards
func hermeticEnv(t *testing.T) {
	t.Helper()
	var names []string
	for _, kv := range os.Environ() {
		if name, _, _ := strings.Cut(kv, "="); hermeticLooksLikeCredential(name) {
			names = append(names, name)
		}
	}
	envLoaderUnset(t, append(names, hermeticBehavioralVars...)...)
}

func TestHermeticEnvBlanksCredentialAndBehavioralVars(t *testing.T) {
	t.Setenv("HERMETIC_PROBE_API_KEY", "secret")
	t.Setenv("FAL_KEY", "secret")
	t.Setenv("TERMINAL_ENV", "docker")
	t.Setenv("HERMETIC_PROBE_PLAIN", "kept")
	t.Run("inner", func(t *testing.T) {
		hermeticEnv(t)
		for _, name := range []string{"HERMETIC_PROBE_API_KEY", "FAL_KEY", "TERMINAL_ENV"} {
			if _, ok := os.LookupEnv(name); ok {
				t.Fatalf("%s survived", name)
			}
		}
		if os.Getenv("HERMETIC_PROBE_PLAIN") != "kept" {
			t.Fatal("a plain var was blanked")
		}
		os.Setenv("TERMINAL_ENV", "ssh")
	})
	if os.Getenv("HERMETIC_PROBE_API_KEY") != "secret" || os.Getenv("FAL_KEY") != "secret" || os.Getenv("TERMINAL_ENV") != "docker" {
		t.Fatal("blanked vars were not restored")
	}
}
