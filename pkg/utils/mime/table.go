type index struct {
	byExt, byType map[string]string
}

// Extension to type and type to preferred extension maps of the table, built on first use
var lookup = sync.OnceValue(func() *index {
	ix := &index{byExt: make(map[string]string, 256), byType: make(map[string]string, len(table))}
	for _, e := range table {
		for _, ext := range e.exts {
			if _, taken := ix.byExt[ext]; !taken {
				ix.byExt[ext] = e.typ
			}
		}
		if _, taken := ix.byType[e.typ]; !taken {
			ix.byType[e.typ] = e.exts[0]
		}
	}
	return ix
})
