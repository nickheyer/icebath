// Command keygen writes pkg/ui/txt/keys.go, one key per entry of the English catalog of the terminal UI
package main

import (
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"unicode"
	"unicode/utf8"

	"gopkg.in/yaml.v3"
)

// English catalog, read from the directory go generate runs in
const catalogPath = "../../tui/locales/en.tui.yaml"

// Names the package declares itself, which no key may take
var reserved = map[string]bool{"Key": true, "Named": true, "All": true}

// Identifier of a dotted name, each word capitalized and joined, the dots kept as the separator given
func identifier(name, dot string) string {
	var segments []string
	for segment := range strings.SplitSeq(name, ".") {
		var b strings.Builder
		for _, word := range strings.FieldsFunc(segment, func(r rune) bool { return r == '_' || r == '-' }) {
			first, size := utf8.DecodeRuneInString(word)
			b.WriteRune(unicode.ToUpper(first))
			b.WriteString(word[size:])
		}
		segments = append(segments, b.String())
	}
	return strings.Join(segments, dot)
}

// Identifier of every name, joined words for most and an underscore at each dot for the names whose joined words would be the same
func identifiers(names []string) (map[string]string, error) {
	joined := map[string][]string{}
	for _, name := range names {
		id := identifier(name, "")
		joined[id] = append(joined[id], name)
	}
	out, taken := map[string]string{}, map[string]string{}
	for _, name := range names {
		id := identifier(name, "")
		if len(joined[id]) > 1 {
			id = identifier(name, "_")
		}
		switch {
		case id == "" || !unicode.IsUpper(rune(id[0])) || strings.ContainsFunc(id, func(r rune) bool { return r != '_' && !unicode.IsLetter(r) && !unicode.IsDigit(r) }):
			return nil, fmt.Errorf("%s gives no Go identifier (%q)", name, id)
		case reserved[id]:
			return nil, fmt.Errorf("%s would take the name %s the package declares itself", name, id)
		case taken[id] != "":
			return nil, fmt.Errorf("%s and %s would both be %s, rename one of them", taken[id], name, id)
		}
		out[name], taken[id] = id, name
	}
	return out, nil
}

// Source of keys.go for the names of the catalog
func render(names []string) ([]byte, error) {
	ids, err := identifiers(names)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Code generated by pkg/ui/txt/internal/keygen from pkg/tui/locales/en.tui.yaml. DO NOT EDIT.\n\npackage txt\n\nvar (\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%s = Key{%q}\n", ids[name], name)
	}
	b.WriteString(")\n\n// Every key in the order of their names\nvar all = []Key{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%s,\n", ids[name])
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

// Names of the catalog, strings and formats together, sorted
func catalogNames(path string) ([]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var catalog struct {
		Strings map[string]string `yaml:"strings"`
		Formats map[string]string `yaml:"formats"`
	}
	if err := yaml.Unmarshal(raw, &catalog); err != nil {
		return nil, err
	}
	names := make([]string, 0, len(catalog.Strings)+len(catalog.Formats))
	for name := range catalog.Strings {
		names = append(names, name)
	}
	for name := range catalog.Formats {
		if _, both := catalog.Strings[name]; both {
			return nil, fmt.Errorf("%s is both a string and a format", name)
		}
		names = append(names, name)
	}
	sort.Strings(names)
	return names, nil
}

// Writes keys.go in the directory go generate runs from
func main() {
	names, err := catalogNames(catalogPath)
	if err == nil {
		var source []byte
		if source, err = render(names); err == nil {
			err = os.WriteFile("keys.go", source, 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "keygen:", err)
		os.Exit(1)
	}
}
