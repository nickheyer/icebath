// Outcome kind of one marker evaluation, true, false or the packaging exception class it raises
func markerOutcome(marker string, environment map[string]string) string {
	ok, err := EvaluateMarker(marker, markerTableDefaults, environment)
	var undefined *UndefinedMarkerError
	var invalid *InvalidMarkerError
	switch {
	case errors.As(err, &undefined):
		return undefined.Class
	case errors.As(err, &invalid):
		return "InvalidMarker"
	case err != nil:
		return err.Error()
	case ok:
		return "true"
	}
	return "false"
}

