package agent

import (
	"encoding/json"
	"testing"
)

// Content normalized through JSON so typed and generic part lists compare equal
func jsonParts(t *testing.T, v any) any {
	t.Helper()
	raw, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	var out any
	if err := json.Unmarshal(raw, &out); err != nil {
		t.Fatal(err)
	}
	return out
}
