// Repository relative paths of the generated TypeScript and OpenRPC files
const (
	TSPath      = "apps/shared/src/gateway-contract.generated.ts"
	OpenRPCPath = "apps/shared/src/gateway-contract.openrpc.json"
)

const header = "// GENERATED by pkg/tuigateway/contractgen from the pkg/tuigateway contracts — DO NOT EDIT.\n" +
	"// Regenerate: go generate ./pkg/tuigateway\n" +
	"// TestGeneratedFilesAreCurrent in pkg/tuigateway fails when this file is stale.\n"

// A construct outside the JSON schema subset the renderer reads, fixed at the model and never in the output
type unsupportedError struct{ msg string }

func (e *unsupportedError) Error() string { return e.msg }

// Rendered text of both generated files keyed by repository relative path
func Render() (files map[string]string, err error) {
	defer func() {
		if r := recover(); r != nil {
			if u, ok := r.(*unsupportedError); ok {
				files, err = nil, u
				return
			}
			panic(r)
		}
	}()
	if err := checkEnumParity(); err != nil {
		return nil, err
	}
	return map[string]string{TSPath: tidy(renderTS()), OpenRPCPath: renderOpenRPC()}, nil
}

// Hex SHA-256 of a generated file text, the form the committed digests take
func Digest(text string) string {
	sum := sha256.Sum256([]byte(text))
	return hex.EncodeToString(sum[:])
}

// One contract enum and the domain values it must equal
type enumPair struct {
	contractName string
	contract     *pydantic.EnumType
	domainName   string
	domain       []string
}

func enumPairs() []enumPair {
	targets := make([]string, len(tools.TargetStates))
	for i, s := range tools.TargetStates {
		targets[i] = string(s)
	}
	reasons := make([]string, len(tools.SettleReasons))
	for i, r := range tools.SettleReasons {
		reasons[i] = string(r)
	}
	return []enumPair{
		{"ConnectionTargetState", tuigateway.ConnectionTargetState, "TargetState", targets},
		{"ConnectionSettleReason", tuigateway.ConnectionSettleReason, "SettleReason", reasons},
		{"ConnectorAccountStatus", tuigateway.ConnectorAccountStatus, "ConnectionStatus", tools.ConnectionStatuses},
		{"ConnectorToolFacet", tuigateway.ConnectorToolFacet, "ConnectorTool.facet", tools.PortalFacets},
		{"ConnectorToolsSource", tuigateway.ConnectorToolsSource, "ToolsRead.source", tools.ToolsReadSources},
	}
}

// Refuses to render when a contract enum and its domain twin hold different values
func checkEnumParity() error {
	for _, p := range enumPairs() {
		if err := parityOf(p); err != nil {
			return err
		}
	}
	return nil
}

// The symmetric difference of one pair as the generation error, nil when both hold the same values
func parityOf(p enumPair) error {
	contract, domain := map[string]bool{}, map[string]bool{}
	for _, v := range p.contract.Values() {
		contract[v] = true
	}
	for _, v := range p.domain {
		domain[v] = true
	}
	var diff []string
	for v := range contract {
		if !domain[v] {
			diff = append(diff, v)
		}
	}
	for v := range domain {
		if !contract[v] {
			diff = append(diff, v)
		}
	}
	if len(diff) == 0 {
		return nil
	}
	sort.Strings(diff)
	items := make([]any, len(diff))
	for i, v := range diff {
		items[i] = v
	}
	return fmt.Errorf("enum parity failed: %s vs %s: %s", p.contractName, p.domainName, pyrepr.Repr(items))
}

// Every params, result and payload model in catalog order with duplicates dropped
func catalogModels() []*pydantic.Model {
	var models []*pydantic.Model
	for _, m := range append(tuigateway.MethodsInOrder(), tuigateway.CanonicalMethodsInOrder()...) {
		models = append(models, m.Params, m.Result)
	}
	for _, r := range tuigateway.ServerRequestsInOrder() {
		models = append(models, r.Params, r.Result)
	}
	for _, e := range tuigateway.EventsInOrder() {
		if e.Payload != nil {
			models = append(models, e.Payload)
		}
	}
	var out []*pydantic.Model
	for _, m := range models {
		if !slices.Contains(out, m) {
			out = append(out, m)
		}
	}
	return out
}

// TypeScript renderer over the shared definitions, emitting each definition once in first use order
type renderer struct {
	defs    *pyjson.Object
	order   []string
	emitted map[string]string
}

func (r *renderer) refName(ref string) string {
	const prefix = "#/$defs/"
	if !strings.HasPrefix(ref, prefix) {
		panic(&unsupportedError{"reference outside $defs: " + ref})
	}
	return ref[len(prefix):]
}

func str(o *pyjson.Object, key string) (string, bool) {
	v, ok := o.Get(key)
	s, isStr := v.(string)
	return s, ok && isStr
}

// TypeScript type of a JSON schema node
func (r *renderer) typeOf(s *pyjson.Object, depth int) string {
	if ref, ok := str(s, "$ref"); ok {
		name := r.refName(ref)
		r.ensure(name)
		return name
	}
	if v, ok := s.Get("const"); ok {
		return lit(v)
	}
	if v, ok := s.Get("enum"); ok {
		parts := []string{}
		for _, e := range v.([]any) {
			parts = append(parts, lit(e))
		}
		return strings.Join(parts, " | ")
	}
	_, hasAny := s.Get("anyOf")
	_, hasOne := s.Get("oneOf")
	if hasAny || hasOne {
		var variants []any
		if v, _ := s.Get("anyOf"); v != nil && len(v.([]any)) > 0 {
			variants = v.([]any)
		} else if v, _ := s.Get("oneOf"); v != nil {
			variants = v.([]any)
		}
		var rendered []string
		for _, v := range variants {
			t := r.typeOf(v.(*pyjson.Object), depth)
			if !slices.Contains(rendered, t) {
				rendered = append(rendered, t)
			}
		}
		return strings.Join(rendered, " | ")
	}
	t, hasType := s.Get("type")
	if list, ok := t.([]any); ok {
		parts := make([]string, len(list))
		for i, x := range list {
			c := s.Copy()
			c.Set("type", x)
			parts[i] = r.typeOf(c, depth)
		}
		return strings.Join(parts, " | ")
	}
	switch t {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "array":
		items, ok := s.Get("items")
		if !ok || items == nil {
			return "unknown[]"
		}
		if prefix, ok := s.Get("prefixItems"); ok {
			parts := []string{}
			for _, x := range prefix.([]any) {
				parts = append(parts, r.typeOf(x.(*pyjson.Object), 0))
			}
			return "[" + strings.Join(parts, ", ") + "]"
		}
		inner := r.typeOf(items.(*pyjson.Object), depth)
		if strings.Contains(inner, " | ") {
			return "(" + inner + ")[]"
		}
		return inner + "[]"
	}
	_, hasProps := s.Get("properties")
	_, hasExtra := s.Get("additionalProperties")
	if t == "object" || hasProps || hasExtra {
		return r.objectLiteral(s, depth)
	}
	onlyMeta := true
	for _, k := range s.Keys {
		if k != "title" && k != "description" && k != "default" {
			onlyMeta = false
		}
	}
	if !hasType && onlyMeta {
		return "unknown"
	}
	text, _ := pyjson.Dumps(s)
	if len([]rune(text)) > 200 {
		text = string([]rune(text)[:200])
	}
	panic(&unsupportedError{"unsupported JSON-Schema construct: " + text})
}

// Object literal or Record type of an object schema
func (r *renderer) objectLiteral(s *pyjson.Object, depth int) string {
	propsV, _ := s.Get("properties")
	props, _ := propsV.(*pyjson.Object)
	extra, hasExtra := s.Get("additionalProperties")
	if props == nil || props.Len() == 0 {
		switch {
		case hasExtra && extra == false:
			return "Record<string, never>"
		case !hasExtra || extra == nil || extra == true:
			return "Record<string, unknown>"
		}
		return "Record<string, " + r.typeOf(extra.(*pyjson.Object), depth+1) + ">"
	}
	required := map[string]bool{}
	if req, ok := s.Get("required"); ok {
		for _, k := range req.([]any) {
			required[k.(string)] = true
		}
	}
	lines := []string{"{"}
	for _, key := range props.Keys {
		opt := "?"
		if required[key] {
			opt = ""
		}
		lines = append(lines, "  "+prop(key)+opt+": "+r.typeOf(props.Vals[key].(*pyjson.Object), depth+1))
	}
	if hasExtra && extra != nil && extra != false {
		value := "unknown"
		if extra != true {
			value = r.typeOf(extra.(*pyjson.Object), 0)
		}
		lines = append(lines, "  [key: string]: "+value)
	}
	lines = append(lines, "}")
	return strings.Join(lines, "\n")
}

// Emits one named definition after reserving its place, which also guards cycles
func (r *renderer) ensure(name string) {
	if _, done := r.emitted[name]; done {
		return
	}
	r.emitted[name] = ""
	r.order = append(r.order, name)
	v, ok := r.defs.Get(name)
	if !ok {
		panic(&unsupportedError{"unknown definition " + name})
	}
	s := v.(*pyjson.Object)
	desc, _ := str(s, "description")
	body := ""
	if enum, ok := s.Get("enum"); ok {
		body = "export type " + name + " = " + r.typeOf(pyjson.ObjectOf("enum", enum), 0) + "\n"
	} else if props, ok := s.Get("properties"); ok && props.(*pyjson.Object).Len() > 0 {
		body = "export interface " + name + " " + r.objectLiteral(s, 0) + "\n"
	} else {
		body = "export type " + name + " = " + r.typeOf(s, 0) + "\n"
	}
	r.emitted[name] = doc(desc, "") + body
}

var ident = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func prop(key string) string {
	if ident.MatchString(key) {
		return key
	}
	return lit(key)
}

func constItems(names []string) string {
	lines := make([]string, len(names))
	for i, n := range names {
		lines[i] = "  " + lit(n)
	}
	return strings.Join(lines, ",\n") + "\n"
}

// TypeScript literal in single quotes for text and JSON for every other value
func lit(v any) string {
	if s, ok := v.(string); ok {
		return "'" + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), "'", `\'`) + "'"
	}
	text, err := pyjson.Dumps(v)
	if err != nil {
		panic(err)
	}
	return text
}

// One line doc comment of whitespace collapsed text, empty for no text
func doc(text, indent string) string {
	if text == "" {
		return ""
	}
	return indent + "/** " + strings.Join(pystr.SplitWhitespace(text, -1), " ") + " */\n"
}

func summary(text string) string { return strings.Join(pystr.SplitWhitespace(text, -1), " ") }

// Text without trailing whitespace on any line and with exactly one trailing newline
func tidy(text string) string {
	lines := pystr.Splitlines(text, false)
	for i, l := range lines {
		lines[i] = pystr.Rstrip(l)
	}
	return pystr.RstripChars(strings.Join(lines, "\n"), "\n") + "\n"
}

func sortedNames[T any](table map[string]*T) []string {
	names := make([]string, 0, len(table))
	for n := range table {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

type pairContract struct {
	name, doc      string
	params, result *pydantic.Model
}

func methodRows(table map[string]*tuigateway.MethodContract) []pairContract {
	var rows []pairContract
	for _, n := range sortedNames(table) {
		m := table[n]
		rows = append(rows, pairContract{m.Name, m.Doc, m.Params, m.Result})
	}
	return rows
}

func requestRows() []pairContract {
	var rows []pairContract
	for _, n := range sortedNames(tuigateway.ServerRequests) {
		s := tuigateway.ServerRequests[n]
		rows = append(rows, pairContract{s.Name, s.Doc, s.Params, s.Result})
	}
	return rows
}

// The TypeScript contract module
func renderTS() string {
	models := catalogModels()
	gen := pydantic.NewSchemaGenerator("#/$defs/{model}")
	nameOf := map[*pydantic.Model]string{}
	r := &renderer{emitted: map[string]string{}}
	tops := make([]*pyjson.Object, len(models))
	for i, m := range models {
		tops[i] = gen.ModelRef(m)
	}
	r.defs = gen.Definitions()
	for i, m := range models {
		ref, _ := str(tops[i], "$ref")
		nameOf[m] = r.refName(ref)
	}
	for _, m := range models {
		r.ensure(nameOf[m])
	}
	var b strings.Builder
	b.WriteString(header + "/* eslint-disable */\n// ── Types ──\n")
	for _, name := range r.order {
		b.WriteString(r.emitted[name])
	}
	reasons := []any{}
	for _, v := range tuigateway.ConnectorErrorReason.Values() {
		reasons = append(reasons, v)
	}
	b.WriteString("export type ConnectorErrorReason = " + r.typeOf(pyjson.ObjectOf("enum", reasons), 0) + "\n")
	section := func(title, iface, keyType, constName string, rows []pairContract, names []string) {
		b.WriteString("\n// ── " + title + " ──\n")
		b.WriteString("export interface " + iface + " {\n")
		for _, row := range rows {
			b.WriteString(doc(row.doc, "  "))
			b.WriteString("  " + prop(row.name) + ": { params: " + nameOf[row.params] + "; result: " + nameOf[row.result] + " }\n")
		}
		b.WriteString("}\n")
		b.WriteString("export type " + keyType + " = keyof " + iface + "\n")
		b.WriteString("export const " + constName + " = [\n" + constItems(names) + "] as const satisfies readonly " + keyType + "[]\n")
	}
	section("Client→server methods", "RpcMethods", "RpcMethod", "RPC_METHODS", methodRows(tuigateway.Methods), sortedNames(tuigateway.Methods))
	section("Canonical (icebath-gateway-v1) methods only the session authority serves", "CanonicalRpcMethods", "CanonicalRpcMethod",
		"CANONICAL_RPC_METHODS", methodRows(tuigateway.CanonicalMethods), sortedNames(tuigateway.CanonicalMethods))
	section("Server→client requests", "ServerRequestMap", "ServerRequestMethod", "SERVER_REQUEST_METHODS", requestRows(), sortedNames(tuigateway.ServerRequests))
	b.WriteString("\n// ── Notifications (`event` frames) ──\n")
	b.WriteString("export interface BackendGatewayEventMap {\n")
	for _, n := range sortedNames(tuigateway.Events) {
		e := tuigateway.Events[n]
		b.WriteString(doc(e.Doc, "  "))
		payload := "Record<string, never>"
		if e.Payload != nil {
			payload = nameOf[e.Payload]
		}
		b.WriteString("  " + prop(e.Name) + ": " + payload + "\n")
	}
	b.WriteString("}\n")
	b.WriteString("export type BackendGatewayEventName = keyof BackendGatewayEventMap\n")
	b.WriteString("export const GATEWAY_EVENT_TYPES = [\n" + constItems(sortedNames(tuigateway.Events)) + "] as const satisfies readonly BackendGatewayEventName[]\n")
	return b.String()
}

// The OpenRPC document of every method, canonical method, server request and notification
func renderOpenRPC() string {
	gen := pydantic.NewSchemaGenerator("#/components/schemas/{model}")
	for _, m := range catalogModels() {
		gen.ModelRef(m)
	}
	components := gen.Definitions()
	reasons := []any{}
	for _, v := range tuigateway.ConnectorErrorReason.Values() {
		reasons = append(reasons, v)
	}
	components.Set("ConnectorErrorReason", pyjson.ObjectOf("type", "string", "enum", reasons))
	ref := func(m *pydantic.Model) *pyjson.Object {
		return pyjson.ObjectOf("$ref", "#/components/schemas/"+m.Name)
	}
	pairs := func(rows []pairContract) []any {
		out := []any{}
		for _, row := range rows {
			out = append(out, pyjson.ObjectOf("name", row.name, "summary", summary(row.doc),
				"params", []any{pyjson.ObjectOf("name", "params", "schema", ref(row.params))},
				"result", pyjson.ObjectOf("name", "result", "schema", ref(row.result))))
		}
		return out
	}
	notifications := []any{}
	for _, n := range sortedNames(tuigateway.Events) {
		e := tuigateway.Events[n]
		schema := pyjson.ObjectOf("type", "object", "additionalProperties", false)
		if e.Payload != nil {
			schema = ref(e.Payload)
		}
		notifications = append(notifications, pyjson.ObjectOf("name", e.Name, "summary", summary(e.Doc),
			"params", []any{pyjson.ObjectOf("name", "payload", "schema", schema)}))
	}
	document := pyjson.ObjectOf(
		"openrpc", "1.3.2",
		"info", pyjson.ObjectOf("title", "Icebath TUI/Desktop gateway", "version", "1",
			"description", "Generated from the pkg/tuigateway contracts by pkg/tuigateway/contractgen."),
		"methods", pairs(methodRows(tuigateway.Methods)),
		"components", pyjson.ObjectOf("schemas", components),
		"x-canonical-methods", pairs(methodRows(tuigateway.CanonicalMethods)),
		"x-server-requests", pairs(requestRows()),
		"x-notifications", notifications,
	)
	text, err := pyjson.Dumps(document, pyjson.Indent(2))
	if err != nil {
		panic(err)
	}
	return text + "\n"
}

// Go source of the digest table for the rendered files, the file go generate writes beside this one
func DigestSource(files map[string]string) string {
	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	var b strings.Builder
	b.WriteString("// Code generated by go generate ./pkg/tuigateway. DO NOT EDIT.\n\npackage contractgen\n\n")
	b.WriteString("// SHA-256 of each committed generated file, compared with a fresh render by the staleness tests\n")
	b.WriteString("var Committed = map[string]string{\n")
	for _, p := range paths {
		b.WriteString("\t" + strconvQuote(p) + ": " + strconvQuote(Digest(files[p])) + ",\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func strconvQuote(s string) string { return `"` + s + `"` }
