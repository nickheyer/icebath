package gateway

import (
	"reflect"
	"runtime"
)

var basePlatformAdapterPtr = reflect.TypeOf(&BasePlatformAdapter{})

// Whether the adapter type defines the named method itself rather than inheriting the base adapter's
func AdapterOverridesBaseMethod(adapter any, name string) bool {
	if adapter == nil {
		return false
	}
	return typeDefinesMethod(reflect.TypeOf(adapter), name, 0)
}

func typeDefinesMethod(t reflect.Type, name string, depth int) bool {
	if t == basePlatformAdapterPtr || depth > 16 {
		return false
	}
	method, ok := t.MethodByName(name)
	if !ok {
		return false
	}
	if fn := runtime.FuncForPC(method.Func.Pointer()); fn != nil {
		if file, _ := fn.FileLine(method.Func.Pointer()); file != "<autogenerated>" {
			return true
		}
	}
	elem := t
	if elem.Kind() == reflect.Pointer {
		elem = elem.Elem()
	}
	if elem.Kind() != reflect.Struct {
		return false
	}
	for i := range elem.NumField() {
		field := elem.Field(i)
		if !field.Anonymous {
			continue
		}
		embedded := field.Type
		if _, has := embedded.MethodByName(name); !has {
			if embedded.Kind() != reflect.Pointer {
				embedded = reflect.PointerTo(embedded)
			}
			if _, has = embedded.MethodByName(name); !has {
				continue
			}
		}
		return typeDefinesMethod(embedded, name, depth+1)
	}
	return false
}
