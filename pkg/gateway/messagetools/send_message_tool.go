const mediaPlatformsNote = "telegram, discord, matrix, weixin, signal, yuanbao, feishu, whatsapp, slack and qqbot"

// Optional parts of one platform send, the thread, media files, forced document mode, mentions and typed tool request
type SendOptions struct {
	ThreadID      *string
	MediaFiles    []gateway.MediaRef
	ForceDocument bool
	Mentions      []string
	Args          map[string]any
}

// Untrusted send failure detail bounded to max characters
func boundedSendError(detail any) string {
	text := "send failed"
	if pyrepr.Truthy(detail) {
		text = pyrepr.Str(detail)
	}
	if utf8.RuneCountInString(text) <= 900 {
		return text
	}
	return string([]rune(text)[:897]) + "..."
}

// Whether the adapter defines its own method instead of the promoted base adapter one
func adapterOverrides(adapter any, method string) bool {
	if adapter == nil || reflect.TypeOf(adapter) == reflect.TypeOf(&gateway.BasePlatformAdapter{}) {
		return false
	}
	m, ok := reflect.TypeOf(adapter).MethodByName(method)
	if !ok {
		return false
	}
	pc := m.Func.Pointer()
	fn := runtime.FuncForPC(pc)
	if fn == nil {
		return false
	}
	file, _ := fn.FileLine(pc)
	return file != "<autogenerated>"
}

// Go method of a python adapter media method name
var adapterMediaGoMethod = map[string]string{"send_image_file": "SendImageFile", "send_video": "SendVideo",
	"send_voice": "SendVoice", "send_document": "SendDocument"}

// Text and every media file through the live adapter's native media methods, refusing kinds it does not implement
func sendLiveAdapterMedia(ctx context.Context, live any, chatID, message string, mediaFiles []gateway.MediaRef, threadID *string, metadata map[string]any, forceDocument bool) (map[string]any, error) {
	adapter, ok := live.(gateway.PlatformAdapter)
	if !ok {
		return nil, fmt.Errorf("'%T' object has no attribute 'send'", live)
	}
	caption, separateText := mediaCaptionSplit(message, mediaFiles, defaultCaptionLimit)
	var last *gateway.SendResult
	if separateText != "" && pystr.Strip(separateText) != "" {
		r, err := adapter.Send(ctx, chatID, separateText, "", metadata)
		if err != nil {
			return nil, err
		}
		if last = &r; !r.Success {
			return map[string]any{"error": "Adapter send failed: " + boundedSendError(r.Error)}, nil
		}
	}
	total := len(mediaFiles)
	var unconfirmed []int
	replyTo := ""
	if threadID != nil {
		replyTo = *threadID
	}
	for index, descriptor := range mediaFiles {
		if descriptor.Path == "" {
			return map[string]any{"error": fmt.Sprintf("Adapter media send failed: invalid media descriptor %d/%d", index+1, total)}, nil
		}
		if !pathExists(descriptor.Path) {
			return map[string]any{"error": fmt.Sprintf("Adapter media send failed: media file %d/%d was not found", index+1, total)}, nil
		}
		ext := lowerExt(descriptor.Path)
		methodName, mediaKind := adapterMediaMethod(ext, descriptor.IsVoice || audioExts[ext], forceDocument)
		if !adapterOverrides(live, adapterMediaGoMethod[methodName]) {
			return map[string]any{"error": fmt.Sprintf("Live adapter does not implement native %s delivery; media file %d/%d was not sent",
				mediaKind, index+1, total)}, nil
		}
		itemCaption := ""
		if index == 0 && caption != nil {
			itemCaption = *caption
		}
		r, err := guardedMedia(func() (gateway.SendResult, error) {
			return callAdapterMedia(ctx, adapter, methodName, chatID, descriptor.Path, itemCaption, replyTo, metadata)
		})
		var detail string
		switch {
		case err != nil && errors.Is(err, context.Canceled):
			return nil, err
		case err != nil:
			detail = boundedSendError(err)
		case r.Success:
			last = &r
			if raw, ok := r.RawResponse.(map[string]any); ok && pyrepr.Truthy(raw["ambiguous"]) {
				unconfirmed = append(unconfirmed, index+1)
			}
			continue
		default:
			last = &r
			errDetail := r.Error
			if !pyrepr.Truthy(errDetail) {
				errDetail = "media send failed"
			}
			detail = boundedSendError(errDetail)
		}
		return map[string]any{"error": fmt.Sprintf("Adapter media send failed after %d/%d files: %s", index, total, detail)}, nil
	}
	if last == nil {
		return map[string]any{"error": noDeliverable}, nil
	}
	result := map[string]any{"success": true, "message_id": last.MessageID, "media_delivered": true}
	if len(unconfirmed) > 0 {
		result["delivery_unconfirmed"] = fmt.Sprintf("media file(s) %s of %d were sent but the platform never confirmed "+
			"receipt; they may already be in the chat, so do not resend them", pyrepr.Repr(unconfirmed), total)
	}
	return result, nil
}

// Adapter media call with a panic surfaced as its error
func guardedMedia(fn func() (gateway.SendResult, error)) (r gateway.SendResult, err error) {
	defer func() {
		if p := recover(); p != nil {
			err = fmt.Errorf("%v", p)
		}
	}()
	return fn()
}

// Runs the send on the gateway loop, directly when there is no loop or ctx already runs on it
func dispatchOnGatewayLoop(ctx context.Context, runner any, makeCoro func(ctx context.Context) (any, error), logMessage string) (any, error) {
	var gatewayLoop gateway.EventLoop
	loopRunner, ok := runner.(gateway.GatewayLoopRunner)
	if ok {
		gatewayLoop = loopRunner.GatewayLoop()
	}
	if gatewayLoop == nil || loopRunner.OnGatewayLoop(ctx) {
		return makeCoro(ctx)
	}
	if !gatewayLoop.IsRunning() {
		return map[string]any{"error": "Gateway loop is not running; cannot dispatch adapter send"}, nil
	}
	type outcome struct {
		v   any
		err error
	}
	done := make(chan outcome, 1)
	loopCtx := context.WithoutCancel(ctx)
	start := func() {
		go func() {
			defer func() {
				if p := recover(); p != nil {
					done <- outcome{err: fmt.Errorf("%v", p)}
				}
			}()
			v, err := makeCoro(loopCtx)
			done <- outcome{v, err}
		}()
	}
	if err := gatewayLoop.CallSoonThreadsafe(start); err != nil {
		sendLog().Debug(fmt.Sprintf("%s: %s", logMessage, err))
		return map[string]any{"error": "Gateway loop unavailable for send dispatch"}, nil
	}
	select {
	case o := <-done:
		return o.v, o.err
	case <-ctx.Done():
		return nil, ctx.Err()
	}
}

// Live in process adapter first, else the plugin standalone sender, else an error naming both
func sendViaAdapter(ctx context.Context, platform gateway.Platform, pconfig *gateway.PlatformConfig, chatID, chunk string, threadID *string, mediaFiles []gateway.MediaRef, forceDocument bool) (map[string]any, error) {
	platformName := string(platform)
	runner, adapter := liveAdapter(ctx, platform, "")
	if adapter != nil {
		result, err := func() (res any, err error) {
			defer func() {
				if p := recover(); p != nil {
					err = fmt.Errorf("%v", p)
				}
			}()
			metadata := map[string]any{}
			if threadID != nil && *threadID != "" {
				metadata["thread_id"] = *threadID
			}
			if platformName == "ntfy" && chatID != "" {
				metadata["publish_topic"] = chatID
			}
			if len(metadata) == 0 {
				metadata = nil
			}
			var makeCoro func(ctx context.Context) (any, error)
			logMessage := "send_message: failed to schedule on gateway loop"
			if len(mediaFiles) > 0 {
				logMessage = "send_message: failed to schedule media send on gateway loop"
				makeCoro = func(ctx context.Context) (any, error) {
					return sendLiveAdapterMedia(ctx, adapter, chatID, chunk, mediaFiles, threadID, metadata, forceDocument)
				}
			} else {
				makeCoro = func(ctx context.Context) (any, error) {
					pa, ok := adapter.(gateway.PlatformAdapter)
					if !ok {
						return nil, fmt.Errorf("'%T' object has no attribute 'send'", adapter)
					}
					return pa.Send(ctx, chatID, chunk, "", metadata)
				}
			}
			return dispatchOnGatewayLoop(ctx, runner, makeCoro, logMessage)
		}()
		if err != nil {
			if errors.Is(err, context.Canceled) {
				return nil, err
			}
			return map[string]any{"error": "Plugin platform send failed: " + boundedSendError(err)}, nil
		}
		if m, ok := result.(map[string]any); ok {
			return m, nil
		}
		r, _ := result.(gateway.SendResult)
		if r.Success {
			return map[string]any{"success": true, "message_id": r.MessageID}, nil
		}
		return map[string]any{"error": "Adapter send failed: " + boundedSendError(r.Error)}, nil
	}
	sender := func() (fn func(context.Context, map[string]any) (map[string]any, error)) {
		defer func() {
			if recover() != nil {
				fn = nil
			}
		}()
		fn, _ = pluginStandaloneSender(ctx, platformName, "", true)
		return fn
	}()
	if sender == nil {
		return map[string]any{"error": fmt.Sprintf("No live adapter for platform '%s'. Is the gateway running with this platform "+
			"connected? For out-of-process delivery (e.g. cron in a separate process), the platform "+
			"plugin must register a standalone_sender_fn on its PlatformEntry.", platformName)}, nil
	}
	result, err := func() (res map[string]any, err error) {
		defer func() {
			if p := recover(); p != nil {
				err = fmt.Errorf("%v", p)
			}
		}()
		return sender(ctx, standaloneKwargs(pconfig, chatID, chunk, map[string]any{"thread_id": optString(threadID),
			"media_files": mediaArg(mediaFiles), "force_document": forceDocument}))
	}()
	if err != nil {
		if errors.Is(err, context.Canceled) {
			return nil, err
		}
		sendLog().Debug(fmt.Sprintf("Plugin standalone send for %s raised", platformName), "error", err)
		return map[string]any{"error": "Plugin standalone send failed: " + boundedSendError(err)}, nil
	}
	if result != nil && (pyrepr.Truthy(result["success"]) || pyrepr.Truthy(result["error"])) {
		if pyrepr.Truthy(result["error"]) {
			out := map[string]any{}
			for k, v := range result {
				out[k] = v
			}
			out["error"] = boundedSendError(result["error"])
			return out, nil
		}
		return result, nil
	}
	typeName := "dict"
	if result == nil {
		typeName = "NoneType"
	}
	return map[string]any{"error": fmt.Sprintf("Plugin standalone send for '%s' returned an invalid result: "+
		"expected a dict with 'success' or 'error' keys, got %s", platformName, typeName)}, nil
}

// Sends each chunk in order, stopping at the first error payload, the last result otherwise
func sendChunks(ctx context.Context, chunks []string, sendOne func(ctx context.Context, chunk string, isLast bool) (map[string]any, error)) (map[string]any, error) {
	var result map[string]any
	for i, chunk := range chunks {
		r, err := sendOne(ctx, chunk, i == len(chunks)-1)
		if err != nil {
			return nil, err
		}
		if result = r; result != nil && pyrepr.Truthy(result["error"]) {
			break
		}
	}
	return result, nil
}

// Registry max message length of the platform, zero for no chunking
func platformMaxLength(ctx context.Context, platform gateway.Platform) (n int) {
	defer func() {
		if recover() != nil {
			n = 0
		}
	}()
	if entry := gateway.Registry.Get(ctx, string(platform)); entry != nil && entry.MaxMessageLength > 0 {
		return entry.MaxMessageLength
	}
	return 0
}

// Plugin standalone send policy after discovering an unregistered name, nil for generic routing
func standaloneSendPolicy(ctx context.Context, platformName string) *gateway.StandaloneSendPolicy {
	if !gateway.Registry.IsRegistered(ctx, platformName) {
		discoverPlugins(ctx)
	}
	if entry := gateway.Registry.Get(ctx, platformName); entry != nil {
		return entry.StandaloneSend
	}
	return nil
}

// Chunked send through a plugin standalone sender, one captionable file and short text riding as its caption
func sendPluginStandalone(ctx context.Context, platformName string, pconfig *gateway.PlatformConfig, chatID, message string, chunks []string, mediaFiles []gateway.MediaRef, threadID *string, maxLen int, forceDocument bool, mentions []string) (map[string]any, error) {
	policy := standaloneSendPolicy(ctx, platformName)
	if policy == nil {
		policy = &gateway.StandaloneSendPolicy{}
	}
	sender, errPayload := pluginStandaloneSender(ctx, platformName, policy.Label, true)
	if errPayload != nil {
		return errPayload, nil
	}
	extra := map[string]any{}
	if policy.ForwardForceDocument {
		extra["force_document"] = forceDocument
	}
	firstOnly := map[string]any{}
	if len(mentions) > 0 {
		firstOnly["mentions"] = mentions
	}
	var emptyMedia []gateway.MediaRef
	if policy.EmptyListBetweenChunks {
		emptyMedia = []gateway.MediaRef{}
	}
	if policy.Captionable {
		limit := maxLen
		if limit == 0 {
			limit = defaultCaptionLimit
		}
		if caption, _ := mediaCaptionSplit(message, mediaFiles, limit); caption != nil {
			kw := map[string]any{"thread_id": optString(threadID), "media_files": mediaArg(mediaFiles), "caption": *caption}
			for k, v := range extra {
				kw[k] = v
			}
			for k, v := range firstOnly {
				kw[k] = v
			}
			return sender(ctx, standaloneKwargs(pconfig, chatID, "", kw))
		}
	}
	return sendChunks(ctx, chunks, func(ctx context.Context, chunk string, isLast bool) (map[string]any, error) {
		kw := map[string]any{}
		for k, v := range extra {
			kw[k] = v
		}
		for k, v := range firstOnly {
			kw[k] = v
		}
		clear(firstOnly)
		media := emptyMedia
		if isLast {
			media = mediaFiles
		}
		kw["thread_id"], kw["media_files"] = optString(threadID), mediaArg(media)
		return sender(ctx, standaloneKwargs(pconfig, chatID, chunk, kw))
	})
}

// Native media chunked route of a built in platform, whether media is required, the non final media and its sender
type chunkedRoute struct {
	mediaRequired bool
	emptyMedia    []gateway.MediaRef
	sender        func(ctx context.Context, p gateway.Platform, pc *gateway.PlatformConfig, cid, chunk string, media []gateway.MediaRef, tid *string, fd bool) (map[string]any, error)
}

func viaAdapterRoute(ctx context.Context, p gateway.Platform, pc *gateway.PlatformConfig, cid, chunk string, media []gateway.MediaRef, tid *string, fd bool) (map[string]any, error) {
	return sendViaAdapter(ctx, p, pc, cid, chunk, tid, media, fd)
}

var chunkedRoutes = map[string]chunkedRoute{
	"matrix": {false, []gateway.MediaRef{}, func(ctx context.Context, _ gateway.Platform, pc *gateway.PlatformConfig, cid, chunk string, media []gateway.MediaRef, tid *string, _ bool) (map[string]any, error) {
		return sendMatrixViaAdapter(ctx, pc, cid, chunk, media, tid)
	}},
	"slack": {false, []gateway.MediaRef{}, viaAdapterRoute},
	"wecom": {true, nil, viaAdapterRoute},
}

// Routes one send to the platform sender, chunking long text with the adapter splitter
func SendToPlatform(ctx context.Context, platform gateway.Platform, pconfig *gateway.PlatformConfig, chatID, message string, opts SendOptions) (map[string]any, error) {
	platformName := string(platform)
	mediaFiles := opts.MediaFiles
	if mediaFiles == nil {
		mediaFiles = []gateway.MediaRef{}
	}
	if platformName == "weixin" {
		return sendPluginStandalone(ctx, platformName, pconfig, chatID, message, []string{message}, mediaFiles, opts.ThreadID, 0, opts.ForceDocument, nil)
	}
	if platform == gateway.PlatformTelegram {
		var token any
		disableLinkPreviews := false
		if pconfig != nil {
			token = pconfig.Token
			disableLinkPreviews = len(pconfig.Extra) > 0 && pyrepr.Truthy(pconfig.Extra["disable_link_previews"])
		}
		return sendTelegram(ctx, token, chatID, message, mediaFiles, opts.ThreadID, disableLinkPreviews, opts.ForceDocument)
	}
	maxLen := platformMaxLength(ctx, platform)
	chunks := []string{message}
	if maxLen > 0 {
		chunks = gateway.TruncateMessage(message, maxLen, nil)
	}
	policy := standaloneSendPolicy(ctx, platformName)
	if policy != nil && (policy.AllSends || (policy.Mentions && len(opts.Mentions) > 0) || (len(mediaFiles) > 0 && policy.Media)) {
		return sendPluginStandalone(ctx, platformName, pconfig, chatID, message, chunks, mediaFiles, opts.ThreadID, maxLen, opts.ForceDocument, opts.Mentions)
	}
	if route, ok := chunkedRoutes[platformName]; ok && (len(mediaFiles) > 0 || !route.mediaRequired) {
		return sendChunks(ctx, chunks, func(ctx context.Context, chunk string, isLast bool) (map[string]any, error) {
			media := route.emptyMedia
			if isLast {
				media = mediaFiles
			}
			return route.sender(ctx, platform, pconfig, chatID, chunk, media, opts.ThreadID, opts.ForceDocument)
		})
	}
	warning := ""
	if len(mediaFiles) > 0 && platformName != "buzz" {
		if pystr.Strip(message) == "" {
			return map[string]any{"error": fmt.Sprintf("send_message MEDIA delivery is currently only supported for %s; "+
				"target %s had only media attachments", mediaPlatformsNote, platformName)}, nil
		}
		warning = fmt.Sprintf("MEDIA attachments were omitted for %s; "+
			"native send_message media delivery is currently only supported for %s", platformName, mediaPlatformsNote)
	}
	var sendOne func(ctx context.Context, chunk string, isLast bool) (map[string]any, error)
	if policy != nil && policy.TextDirect {
		sendOne = func(ctx context.Context, chunk string, _ bool) (map[string]any, error) {
			return registryStandaloneSend(ctx, platformName, pconfig, chatID, chunk, opts.ThreadID)
		}
	} else {
		if entry := gateway.Registry.Get(ctx, platformName); entry != nil && entry.SendMessageHandler != nil {
			args := opts.Args
			if args == nil {
				args = map[string]any{}
			}
			result, err := func() (res map[string]any, err error) {
				defer func() {
					if p := recover(); p != nil {
						err = fmt.Errorf("%v", p)
					}
				}()
				return entry.SendMessageHandler(ctx, args, chatID, platformName, pconfig)
			}()
			if err != nil {
				if errors.Is(err, context.Canceled) {
					return nil, err
				}
				return map[string]any{"error": fmt.Sprintf("Plugin send_message handler failed: %s", err)}, nil
			}
			return result, nil
		}
		sendOne = func(ctx context.Context, chunk string, isLast bool) (map[string]any, error) {
			media := []gateway.MediaRef{}
			if isLast {
				media = mediaFiles
			}
			return viaAdapterRoute(ctx, platform, pconfig, chatID, chunk, media, opts.ThreadID, opts.ForceDocument)
		}
	}
	lastResult, err := sendChunks(ctx, chunks, sendOne)
	if err != nil {
		return nil, err
	}
	if warning != "" && lastResult != nil && pyrepr.Truthy(lastResult["success"]) && !pyrepr.Truthy(lastResult["media_delivered"]) {
		switch w := lastResult["warnings"].(type) {
		case []string:
			lastResult["warnings"] = append(append([]string{}, w...), warning)
		case []any:
			lastResult["warnings"] = append(append([]any{}, w...), warning)
		default:
			lastResult["warnings"] = []string{warning}
		}
	}
	return lastResult, nil
}
