package gateway

import (
	"context"
	"reflect"
	"runtime"
	"sync"

	"github.com/nickheyer/icebath/pkg/internal/pyjson"
)

// Adapter processing bracket of one producer admitted turn, its typing refresh and lifecycle hooks
type producerBracket struct {
	mu       sync.Mutex
	adapter  PlatformAdapter
	event    *MessageEvent
	hooks    bool
	metadata map[string]any
	stop     *InterruptEvent
	typing   *adapterTask
	closed   bool
}

// Whether a reflected method is a compiler generated promotion wrapper
func methodAutogenerated(m reflect.Method) bool {
	fn := runtime.FuncForPC(m.Func.Pointer())
	if fn == nil {
		return false
	}
	file, _ := fn.FileLine(m.Func.Pointer())
	return file == "<autogenerated>"
}

// Embedding depth at which a type reaches a declared method, negative when it has none
func methodDepth(t reflect.Type, method string) (int, reflect.Type) {
	m, ok := t.MethodByName(method)
	if !ok {
		return -1, nil
	}
	if t.Kind() == reflect.Interface || !methodAutogenerated(m) {
		return 0, t
	}
	s := t
	if s.Kind() == reflect.Pointer {
		s = s.Elem()
		if vm, ok := s.MethodByName(method); ok && !methodAutogenerated(vm) {
			return 0, t
		}
	}
	if s.Kind() != reflect.Struct {
		return 0, t
	}
	best, owner := -1, reflect.Type(nil)
	for i := range s.NumField() {
		f := s.Field(i)
		if !f.Anonymous {
			continue
		}
		ft := f.Type
		if ft.Kind() == reflect.Struct {
			ft = reflect.PointerTo(ft)
		}
		if depth, declared := methodDepth(ft, method); depth >= 0 && (best < 0 || depth+1 < best) {
			best, owner = depth+1, declared
		}
	}
	if best < 0 {
		return 0, t
	}
	return best, owner
}

// Whether the adapter's own type declares the method in place of the base adapter's default
func adapterOverrides(adapter PlatformAdapter, method string) bool {
	if adapter == nil {
		return false
	}
	_, owner := methodDepth(reflect.TypeOf(adapter), method)
	return owner != nil && owner != reflect.TypeFor[*BasePlatformAdapter]()
}

// Open brackets of the authority keyed by admission id, a nil one committed and not yet started
func producerTurns(a *SessionAuthority) map[string]*producerBracket {
	if a.producerTurns == nil {
		a.producerTurns = map[string]*producerBracket{}
	}
	return a.producerTurns
}

// Marks a producer's freshly queued row as the executor's to bracket, a resent row left alone
func markProducerAdmission(a *SessionAuthority, event *MessageEvent, row *pyjson.Object) {
	if event == nil || !event.producerDelivery || rowString(row, "status") != AdmissionQueued {
		return
	}
	a.mu.Lock()
	defer a.mu.Unlock()
	turns := producerTurns(a)
	if _, ok := turns[rowString(row, "admission_id")]; !ok {
		turns[rowString(row, "admission_id")] = nil
	}
}

// Bracket whose status anchor is fixed on the turn's own triggering message
func newProducerBracket(adapter PlatformAdapter, event *MessageEvent, hooks bool) *producerBracket {
	return &producerBracket{adapter: adapter, event: event, hooks: hooks, stop: NewInterruptEvent(),
		metadata: typingMetadataForTurn(adapter, event.Source.ChatID, replyAnchorForEvent(event), threadMetadataForEvent(event))}
}

// Stops the typing refresh of the turn once, leaving the hooks open
func (b *producerBracket) stopTyping(ctx context.Context) {
	b.mu.Lock()
	task := b.typing
	b.typing = nil
	b.mu.Unlock()
	if task != nil {
		b.stop.Set()
		b.adapter.Base().stopTypingRefresh(ctx, b.event.Source.ChatID, task, b.metadata, 0.5, 2)
	}
}

// Reports the turn's outcome to the adapter once, after its typing stopped
func (b *producerBracket) close(ctx context.Context, outcome ProcessingOutcome) {
	b.mu.Lock()
	if b.closed {
		b.mu.Unlock()
		return
	}
	b.closed = true
	b.mu.Unlock()
	b.stopTyping(ctx)
	if b.hooks {
		adapter, event := b.adapter, b.event
		adapter.Base().runProcessingHook(ctx, "on_processing_complete", func(c context.Context) error {
			return adapter.OnProcessingComplete(c, event, outcome)
		})
	}
}

// Whether the bracket already reported its outcome
func (b *producerBracket) isClosed() bool {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.closed
}

// Opens the bracket of a producer admitted row starting to execute, nil for any other admission
func openProducerTurn(ctx context.Context, a *SessionAuthority, row *pyjson.Object, event *MessageEvent) (*producerBracket, error) {
	admissionID := rowString(row, "admission_id")
	a.mu.Lock()
	_, marked := producerTurns(a)[admissionID]
	a.mu.Unlock()
	if !marked {
		return nil, nil
	}
	adapter := a.Runner.AdapterForSource(ctx, event.Source)
	typing := adapter != nil && adapterOverrides(adapter, "SendTyping")
	hooks := followupProcessingHooksApply(adapter, event)
	if !(typing || hooks) {
		a.mu.Lock()
		delete(a.producerTurns, admissionID)
		a.mu.Unlock()
		return nil, nil
	}
	bracket := newProducerBracket(adapter, event, hooks)
	a.mu.Lock()
	a.producerTurns[admissionID] = bracket
	a.mu.Unlock()
	if typing {
		bracket.typing = adapter.Base().startTypingRefresh(ctx, event, bracket.stop, bracket.metadata)
	}
	if hooks {
		adapter.Base().runProcessingHook(ctx, "on_processing_start", func(c context.Context) error {
			return adapter.OnProcessingStart(c, event)
		})
		if err := ctx.Err(); err != nil {
			bracket.stop.Set()
			if bracket.typing != nil {
				bracket.typing.cancel()
			}
			a.mu.Lock()
			delete(a.producerTurns, admissionID)
			a.mu.Unlock()
			return nil, err
		}
	}
	return bracket, nil
}

// Hook outcome of the result settlement will commit for an executed turn
func executedOutcome(captured *pyjson.Object) ProcessingOutcome {
	value, ok := captured.Get("terminal_result")
	if !ok {
		value, _ = captured.Get("result")
	}
	result, _ := value.(*pyjson.Object)
	if result == nil {
		return ProcessingSuccess
	}
	if v, _ := result.Get("interrupted"); pyTruthy(v) {
		return ProcessingCancelled
	}
	failed, _ := result.Get("failed")
	errValue, _ := result.Get("error")
	if pyTruthy(failed) || pyTruthy(errValue) {
		return ProcessingFailure
	}
	return ProcessingSuccess
}

// Runs a claimed row's execution inside its producer bracket, reporting a non success outcome when it ends
func producerTurn(ctx context.Context, a *SessionAuthority, row *pyjson.Object, event *MessageEvent, captured *pyjson.Object, run func(ctx context.Context) error) error {
	bracket, err := openProducerTurn(ctx, a, row, event)
	if err != nil {
		return err
	}
	if bracket == nil {
		return run(ctx)
	}
	outcome := ProcessingFailure
	defer func() {
		closing := context.WithoutCancel(ctx)
		bracket.stopTyping(closing)
		if outcome != ProcessingSuccess {
			closeProducerTurn(closing, a, rowString(row, "admission_id"), outcome)
		}
	}()
	if err := run(ctx); err != nil {
		return err
	}
	outcome = executedOutcome(captured)
	return nil
}

// Reports a settled producer turn's outcome once, nothing for any other admission
func closeProducerTurn(ctx context.Context, a *SessionAuthority, admissionID string, outcome ProcessingOutcome) {
	a.mu.Lock()
	bracket := a.producerTurns[admissionID]
	delete(a.producerTurns, admissionID)
	a.mu.Unlock()
	if bracket != nil {
		bracket.close(ctx, outcome)
	}
}

// Reports failure for a started turn that settled without its reply, off the caller's path
func dropProducerTurn(a *SessionAuthority, admissionID string) {
	a.mu.Lock()
	bracket := a.producerTurns[admissionID]
	delete(a.producerTurns, admissionID)
	a.mu.Unlock()
	if bracket == nil || bracket.isClosed() {
		return
	}
	task := spawnAdapterTask(context.Background(), func(ctx context.Context) error {
		bracket.close(ctx, ProcessingFailure)
		return nil
	})
	bracket.adapter.Base().trackBackgroundTask(task)
}
