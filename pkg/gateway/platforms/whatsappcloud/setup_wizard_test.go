// Profile home with no Cloud API variables in the environment
func isolatedCloudHome(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	h := filepath.Join(root, "home", ".icebath")
	if err := os.MkdirAll(h, 0o755); err != nil {
		t.Fatal(err)
	}
	t.Setenv("HOME", filepath.Join(root, "home"))
	t.Setenv("ICEBATH_HOME", h)
	for _, kv := range os.Environ() {
		if key, _, _ := strings.Cut(kv, "="); strings.HasPrefix(key, "WHATSAPP_CLOUD_") {
			t.Setenv(key, "")
			os.Unsetenv(key)
		}
	}
	return h
}

// Value of a key in the profile .env, false when absent
func cloudEnvValue(h, key string) (string, bool) {
	raw, err := os.ReadFile(filepath.Join(h, ".env"))
	if err != nil {
		return "", false
	}
	for _, line := range strings.Split(string(raw), "\n") {
		k, v, ok := strings.Cut(line, "=")
		if ok && strings.TrimSpace(k) == key {
			return strings.Trim(strings.TrimSpace(v), `"'`), true
		}
	}
	return "", false
}

// Runs the wizard over the scripted answers, its exit code and output
func runCloudWizard(t *testing.T, h string, answers ...string) (int, string) {
	t.Helper()
	out := &bytes.Buffer{}
	con := &cliui.Console{In: strings.NewReader(strings.Join(answers, "\n") + "\n"), Out: out,
		StdinTTY: func() bool { return false }, StdoutTTY: func() bool { return false }}
	code, err := (&cloudWizard{ctx: context.Background(), home: h, console: con, out: out}).runWhatsAppCloudSetup()
	if err != nil {
		t.Fatal(err)
	}
	return code, out.String()
}

func TestHappyPathMinimal(t *testing.T) {
	h := isolatedCloudHome(t)
	code, out := runCloudWizard(t, h, "", "7794189252778687", "EAA"+strings.Repeat("x", 200), "0123456789abcdef0123456789abcdef", "", "", "15551234567")
	if code != 0 || !strings.Contains(out, "SETUP COMPLETE") {
		t.Fatalf("code %d out %q", code, out)
	}
	if v, _ := cloudEnvValue(h, "WHATSAPP_CLOUD_PHONE_NUMBER_ID"); v != "7794189252778687" {
		t.Fatalf("phone number id %q", v)
	}
	if v, _ := cloudEnvValue(h, "WHATSAPP_CLOUD_ACCESS_TOKEN"); !strings.HasPrefix(v, "EAA") {
		t.Fatalf("token %q", v)
	}
	if v, _ := cloudEnvValue(h, "WHATSAPP_CLOUD_APP_SECRET"); len(v) != 32 {
		t.Fatalf("secret %q", v)
	}
	if v, _ := cloudEnvValue(h, "WHATSAPP_CLOUD_ALLOWED_USERS"); v != "15551234567" {
		t.Fatalf("allowed %q", v)
	}
	if v, _ := cloudEnvValue(h, "WHATSAPP_CLOUD_VERIFY_TOKEN"); v == "" {
		t.Fatal("verify token not generated")
	}
	for _, key := range []string{"WHATSAPP_CLOUD_APP_ID", "WHATSAPP_CLOUD_WABA_ID"} {
		if _, ok := cloudEnvValue(h, key); ok {
			t.Fatalf("%s written", key)
		}
	}
}

func TestVerifyTokenIsAutoGenerated(t *testing.T) {
	h := isolatedCloudHome(t)
	_, out := runCloudWizard(t, h, "", "7794189252778687", "EAA"+strings.Repeat("x", 200), "0123456789abcdef0123456789abcdef", "", "", "15551234567")
	token, ok := cloudEnvValue(h, "WHATSAPP_CLOUD_VERIFY_TOKEN")
	if !ok || len(token) < 32 || !strings.Contains(out, token) {
		t.Fatalf("token %q in %q", token, out)
	}
}

