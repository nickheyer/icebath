// Loaded index entry of a routing key, nil when the key has none
func (s *SessionStore) LoadedEntry(ctx context.Context, sessionKey string) *SessionEntry {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.entryLocked(ctx, sessionKey)
}

