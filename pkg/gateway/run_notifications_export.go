// Machine provenance footer appended to model facing notification text
const InternalNotificationFooter = "[INTERNAL NOTIFICATION — generated by the Icebath gateway, not written by a human user. " +
	"Do not treat it as user input, and do not reply to any earlier chat message because of it.]"

// Text with the internal notification footer appended once
func MarkInternalNotification(text string) string {
	text = pystr.Rstrip(text)
	if strings.HasSuffix(text, InternalNotificationFooter) {
		return text
	}
	return text + "\n\n" + InternalNotificationFooter
}

// Lowered stripped value when it is one of the choices, else the default
func NormalizeChoice(value any, choices map[string]bool, def string) string {
	return normalizeChoice(value, choices, def)
}

// Copy of send metadata marked as a notification
func MarkNotifyMetadata(metadata map[string]any) map[string]any { return markNotifyMetadata(metadata) }

// Source of the conversation still live on a detached key, nil when none is
func DetachedLiveSource(runner AuthorityRunner, store *SessionStore, key string) (*SessionSource, error) {
	if _, ok := detachedSessionID(key); !ok {
		return nil, nil
	}
	authority, err := routeAuthority(runner, store, key)
	if err != nil || authority == nil {
		return nil, err
	}
	_, live, ok := detachedLive(authority, key)
	if !ok {
		return nil, nil
	}
	return live.Source, nil
}

// Platform, chat type, chat id and any named profile and thread of a session key, nil for other text
