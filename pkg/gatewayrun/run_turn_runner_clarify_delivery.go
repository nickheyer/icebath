package gatewayrun

import (
	"context"
	"fmt"
	"reflect"
	"runtime"
	"sync"
	"time"

	"github.com/nickheyer/icebath/pkg/gateway"
	"github.com/nickheyer/icebath/pkg/tools"
)

// Notices a clarify question carries when its prompt never reached the user
const (
	clarifyUndelivered          = "[clarify prompt could not be delivered]"
	clarifyUndeliveredDeclined  = "[clarify prompt could not be delivered: destination refused]"
	clarifyUndeliveredNoSurface = "[clarify prompt could not be delivered: no chat surface]"
)

// Seconds a scheduled card send may take before it counts as possibly posted
const clarifySendAckWindow = 15

// Keyword arguments of one clarify prompt send
type clarifySendArgs struct {
	chatID     string
	question   string
	choices    []string
	clarifyID  string
	sessionKey string
	metadata   map[string]any
}

// Adapter rendering a clarify prompt, the base numbered text or a native card
type clarifySender interface {
	SendClarify(ctx context.Context, chatID, question string, choices []string, clarifyID, sessionKey string, metadata map[string]any) (gateway.SendResult, error)
}

// Whether the adapter type declares the method itself instead of inheriting the base one
func adapterDeclares(adapter any, method string) bool {
	if adapter == nil || reflect.TypeOf(adapter) == reflect.TypeOf(&gateway.BasePlatformAdapter{}) {
		return false
	}
	m, ok := reflect.TypeOf(adapter).MethodByName(method)
	if !ok {
		return false
	}
	pc := m.Func.Pointer()
	fn := runtime.FuncForPC(pc)
	if fn == nil {
		return false
	}
	file, _ := fn.FileLine(pc)
	return file != "<autogenerated>"
}

// Base numbered text clarify send, nil when the adapter has no native card to fall back from
func textFallbackCoro(adapter gateway.PlatformAdapter, args clarifySendArgs) func(ctx context.Context) (any, error) {
	if adapter == nil || !adapterDeclares(adapter, "SendClarify") {
		return nil
	}
	metadata := map[string]any{}
	for k, v := range args.metadata {
		metadata[k] = v
	}
	metadata["is_approval_prompt"] = true
	return func(ctx context.Context) (any, error) {
		return adapter.Base().SendClarify(ctx, args.chatID, args.question, args.choices, args.clarifyID, args.sessionKey, metadata)
	}
}

// Abort sentinel for a definitive send failure with the registration torn down, empty to proceed to the wait
func abortForOutcome(outcome, sessionKey string) string {
	switch outcome {
	case "declined":
		runLog().Warn("Clarify prompt DECLINED by the connector's egress guard; clearing registration")
		tools.ClearClarifySession(sessionKey)
		return clarifyUndeliveredDeclined
	case "failed":
		runLog().Warn("Clarify send failed definitively; clearing registration")
		tools.ClearClarifySession(sessionKey)
		return clarifyUndelivered
	case "ambiguous":
		runLog().Warn("Clarify prompt send timed out — treating as possibly-delivered (no teardown; the registration stays armed for a late reply)")
	}
	return ""
}

// Abort sentinel of a clarify prompt send, empty when the caller proceeds to the wait
func clarifySendDisposition(fut *concurrentFuture, sessionKey string) string {
	return abortForOutcome(approvalSendOutcome(fut, clarifySendAckWindow), sessionKey)
}

// Resolves a clarify prompt through its send disposition, the text fallback and the bounded wait, true when answered
func clarifySendThenWait(ctx context.Context, env *tools.Env, fut *concurrentFuture, clarifyID, sessionKey string, fallback func() *concurrentFuture) (string, bool) {
	outcome := approvalSendOutcome(fut, clarifySendAckWindow)
	if outcome == "failed" && fallback != nil {
		fut, fallback = fallback(), nil
		if fut != nil {
			outcome = approvalSendOutcome(fut, clarifySendAckWindow)
		}
		if outcome == "sent" {
			runLog().Info(fmt.Sprintf("Clarify card undeliverable; plain-text prompt sent instead (id=%s)", clarifyID))
		}
	}
	if abort := abortForOutcome(outcome, sessionKey); abort != "" {
		return abort, false
	}
	late := newLateFailureWatch(fut, clarifyID, sessionKey, fallback)
	timeout := tools.GetClarifyTimeout(env)
	response := tools.WaitForGatewayClarify(ctx, env, clarifyID, time.Duration(timeout)*time.Second)
	late.disarm()
	if notice := late.undeliverableNotice(); notice != "" {
		return notice, false
	}
	if response != nil && *response == tools.ClarifyCancelled {
		return *response, false
	}
	if response == nil || *response == "" {
		return fmt.Sprintf("[user did not respond within %dm]", timeout/60), false
	}
	return *response, true
}

// Watch over a possibly delivered card send that releases the waiter when it fails after the ack window
type lateFailureWatch struct {
	mu            sync.Mutex
	undeliverable string
	armed         bool
	clarifyID     string
	sessionKey    string
	fallback      func() *concurrentFuture
}

// Watch armed only while the card send is still pending
func newLateFailureWatch(fut *concurrentFuture, clarifyID, sessionKey string, fallback func() *concurrentFuture) *lateFailureWatch {
	w := &lateFailureWatch{clarifyID: clarifyID, sessionKey: sessionKey, fallback: fallback}
	if fut != nil && !fut.isDone() {
		w.armed = true
		onDone(fut, w.onCardDone)
	}
	return w
}

// Runs fn once the future settles
func onDone(fut *concurrentFuture, fn func(*concurrentFuture)) {
	go func() {
		<-fut.done
		fn(fut)
	}()
}

// Stops the watch from acting on a late outcome
func (w *lateFailureWatch) disarm() {
	w.mu.Lock()
	w.armed = false
	w.mu.Unlock()
}

// Delivery notice a late failure left, empty while nothing definitive happened
func (w *lateFailureWatch) undeliverableNotice() string {
	w.mu.Lock()
	defer w.mu.Unlock()
	return w.undeliverable
}

// Whether the watch still acts on late outcomes
func (w *lateFailureWatch) isArmed() bool {
	w.mu.Lock()
	defer w.mu.Unlock()
	return w.armed
}

// Classifies the late card outcome, retrying once as text or releasing the waiter
func (w *lateFailureWatch) onCardDone(fut *concurrentFuture) {
	if !w.isArmed() {
		return
	}
	outcome := approvalSendOutcome(fut, 0)
	if outcome == "sent" {
		return
	}
	runLog().Warn(fmt.Sprintf("Clarify card send resolved %s after the ack window (id=%s)", outcome, w.clarifyID))
	if outcome == "ambiguous" {
		return
	}
	if outcome == "declined" {
		w.release(clarifyUndeliveredDeclined)
		return
	}
	var fallbackFut *concurrentFuture
	if w.fallback != nil {
		fallbackFut = w.fallback()
	}
	if fallbackFut == nil {
		w.release(clarifyUndelivered)
		return
	}
	onDone(fallbackFut, w.onFallbackDone)
}

// Releases the waiter unless the text fallback was sent
func (w *lateFailureWatch) onFallbackDone(fut *concurrentFuture) {
	if !w.isArmed() {
		return
	}
	if approvalSendOutcome(fut, 0) == "sent" {
		runLog().Info(fmt.Sprintf("Clarify card undeliverable; plain-text prompt sent instead (id=%s)", w.clarifyID))
		return
	}
	w.release(clarifyUndelivered)
}

// Records the delivery notice and wakes the waiting agent goroutine
func (w *lateFailureWatch) release(notice string) {
	w.mu.Lock()
	w.undeliverable = notice
	w.mu.Unlock()
	tools.ClearClarifySession(w.sessionKey)
}
