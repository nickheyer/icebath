func Register(cfg *config.Config) {
	cfg.Register(config.Sections{{
		Key:    Key,
		Parent: webconfig.Key,
		Title:  "DuckDuckGo (ddgs)",
		About:  "The built-in metasearch client: DuckDuckGo, Yahoo, Brave, Google, Mojeek, Startpage, Wikipedia and Grokipedia at once, no key, search only",
		Settings: []config.Setting{
			{Key: Region, Title: "Region", About: "Country and language the engines search for, Wikipedia's language among them", Default: "us-en", Options: config.Options(regions...)},
			{Key: SafeSearch, Title: "Safe search", About: "How strictly the engines that can filter adult results do", Default: "moderate", Options: config.Options(
				config.Option{Value: "on", Title: "Strict"},
				config.Option{Value: "moderate", Title: "Moderate"},
				config.Option{Value: "off", Title: "Off"},
			)},
			{Key: TimeLimit, Title: "Time limit", About: "Only results from the last day, week, month or year, from the engines that can filter by date", Default: "", Options: config.Options(
				config.Option{Value: "", Title: "Any time"},
				config.Option{Value: "d", Title: "Past day"},
				config.Option{Value: "w", Title: "Past week"},
				config.Option{Value: "m", Title: "Past month"},
				config.Option{Value: "y", Title: "Past year"},
			)},
			{Key: Proxy, Title: "Proxy", About: "Proxy every search request goes through, such as socks5h://127.0.0.1:9150; tb stands for the Tor Browser's", Default: "", Env: []string{"DDGS_PROXY"}},
		},
	}})
}

