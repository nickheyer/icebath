func inRuneRanges(r rune, ranges [][2]rune) bool {
	for _, span := range ranges {
		if r >= span[0] && r <= span[1] {
			return true
		}
	}
	return false
}

// Index and length of the longest jamo short name prefixing text
func findSyllable(text string, names []string) (int, int) {
	pos, length := -1, -1
	for i, s := range names {
		if len(s) <= length {
			continue
		}
		if strings.HasPrefix(text, s) {
			pos, length = i, len(s)
		}
	}
	return pos, max(length, 0)
}

// Code point of an ideograph name with an uppercase hex suffix inside the given ranges
func derivedIdeograph(name, prefix string, ranges [][2]rune) (rune, bool) {
	hex, ok := strings.CutPrefix(name, prefix)
	if !ok || hex == "" {
		return 0, false
	}
	v, err := strconv.ParseUint(hex, 16, 32)
	if err != nil || fmt.Sprintf("%X", v) != hex || !inRuneRanges(rune(v), ranges) {
		return 0, false
	}
	return rune(v), true
}

// Code point a Unicode character name or alias names, matched case insensitively, the name index built on first use
func (p *parser) lookupName(name string) (rune, bool) {
	upper := strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' {
			return r - 32
		}
		return r
	}, name)
	if rest, ok := strings.CutPrefix(upper, "HANGUL SYLLABLE "); ok {
		l, n := findSyllable(rest, hangulL)
		rest = rest[n:]
		v, n := findSyllable(rest, hangulV)
		rest = rest[n:]
		t, n := findSyllable(rest, hangulT)
		rest = rest[n:]
		if l < 0 || v < 0 || t < 0 || rest != "" {
			return 0, false
		}
		return rune(0xAC00 + (l*len(hangulV)+v)*len(hangulT) + t), true
	}
	if r, ok := derivedIdeograph(upper, "CJK UNIFIED IDEOGRAPH-", cjkUnifiedRanges); ok {
		return r, true
	}
	if r, ok := derivedIdeograph(upper, "TANGUT IDEOGRAPH-", tangutRanges); ok {
		return r, true
	}
	if p.names == nil {
		p.names = map[string]rune{}
		for r := rune(0); r <= utf8.MaxRune; r++ {
			if n := runenames.Name(r); n != "" && n[0] != '<' && !inRuneRanges(r, unicodeNewerRanges) {
				p.names[n] = r
			}
		}
		for n, r := range unicodeAliases {
			p.names[n] = r
		}
	}
	r, ok := p.names[upper]
	return r, ok
}

